package org.example.Util;

import org.example.View.LogConsolePanel;
import java.awt.Color;

/**
 * КОНКРЕТНАЯ СТРАТЕГИЯ (CONCRETE STRATEGY) для успешных операций.
 *
 * Этот класс реализует интерфейс MessageStrategy и предназначен для вывода
 * сообщений об успешно завершенных действиях.
 * Например: "Файл успешно загружен", "Успешно добавлена машина: BMW".
 *
 * В архитектуре MVC этот класс находится в пакете Util.
 * Он вызывается Контроллером (через MessageHandler), когда Модель успешно
 * выполнила бизнес-операцию и нужно порадовать пользователя зеленой надписью.
 *
 * Как и другие стратегии, он полностью инкапсулирует в себе логику форматирования
 * и выбора цвета для данного типа сообщений.
 */
public class SuccessMessageStrategy implements MessageStrategy {

    /**
     * Главный метод паттерна Стратегия.
     *
     * @param message Основной текст сообщения (например, "Данные сохранены").
     * @param error   Детали ошибки. Для успешных операций этот параметр игнорируется
     *                (всегда передается null из MessageHandler), но он обязан быть
     *                в сигнатуре метода, чтобы класс реализовывал интерфейс корректно.
     * @param logPanel Ссылка на панель логов из View, куда нужно вывести текст.
     */
    @Override
    public void execute(String message, String error, LogConsolePanel logPanel) {
        // Формируем строку для вывода.
        // Используем тернарный оператор (условие ? true : false).
        // Если сообщение не null и не пустое, добавляем к нему префикс "[УСПЕХ] "
        // и перенос строки (\n) в конце. Иначе оставляем строку пустой.
        String textToPrint = (message != null && !message.isEmpty()) ? "[УСПЕХ] " + message + "\n" : "";

        // System.out — стандартный поток вывода в консоль IDE.
        // В консоли он будет обычного цвета (в отличие от System.err, который красный).
        System.out.print(textToPrint);

        // Отправляем текст в графическую панель логов.
        // Создаем объект темно-зеленого цвета через RGB:
        // new Color(RED, GREEN, BLUE) -> 0 красного, 128 зеленого, 0 синего.
        // Темно-зеленый цвет выглядит мягче на светлых фонах интерфейса, чем ярко-зеленый (Color.GREEN).
        logPanel.appendColoredText(textToPrint, new Color(0, 128, 0));
    }
}