package org.example.Util;

import org.example.View.LogConsolePanel;

/**
 * ИНТЕРФЕЙС СТРАТЕГИИ (STRATEGY INTERFACE)
 *
 * В паттерне проектирования "Стратегия" (Strategy) интерфейс играет главную роль:
 * он определяет общий "контракт" (поведение) для всех возможных алгоритмов или
 * вариантов логики.
 *
 * В нашем случае, этот интерфейс говорит: "Любой класс, который меня реализует,
 * обязан иметь метод execute для вывода сообщения в лог".
 *
 * ПОЧЕМУ ИНТЕРФЕЙС, А НЕ АБСТРАКТНЫЙ КЛАСС?
 * Потому что у наших стратегий (Info, Success, Error) нет общего внутреннего состояния
 * (полей с данными), их нужно только вызвать. Интерфейс здесь идеален. Кроме того,
 * класс-стратегия может наследоваться от какого-то другого класса, а в Java множественное
 * наследование классов запрещено, но можно реализовывать множество интерфейсов.
 *
 * СВЯЗЬ С MVC:
 * Находясь в пакете Util, этот интерфейс связывает Контроллер (который инициирует логирование)
 * и Представление (LogConsolePanel, куда выводится текст), делая эту связь слабой и гибкой.
 */
public interface MessageStrategy {

    /**
     * Единый метод, который должны реализовать все конкретные стратегии.
     *
     * @param message Основной текст сообщения (например, "Файл загружен").
     * @param error   Текст ошибки (используется только стратегией Error, для остальных null).
     * @param logPanel Ссылка на панель логов, чтобы стратегия могла сама отрисовать текст в GUI.
     */
    void execute(String message, String error, LogConsolePanel logPanel);
}